def get_flashback_text(current_scenario_id: str,
                       data_logger) -> str | None:
    """
    اگر برای سناریوی جاری فلش‌بکی وجود دارد و بازیکن تصمیم
    قبلی را گرفته، متن فلش‌بک را برمی‌گرداند. در غیر این صورت None.
    """
    entry = FLASHBACK_MAP.get(current_scenario_id)
    if not entry:
        return None

    reference_id = entry["reference"]
    prev_choice = data_logger.recall_choice(reference_id)
    if prev_choice < 0:
        return None

    cases = entry["cases"]
    if prev_choice in cases:
        return cases[prev_choice]
    return None