# اکنون فقط فهرست تصمیم‌ها نمایش داده می‌شود — بدون نتیجه‌گیری.


# ============================================================
# منطق اصلی
# ============================================================
# تابع _detect_pattern حذف شد — دیگر نیاز نیست.


def get_multilayer_memory_text(current_scenario_id: str,
                                data_logger) -> str | None:
    """
    اگر سناریوی جاری در MULTILAYER_MAP باشد و بازیکن حداقل
    دو تصمیم از سه تصمیم مرجع را گرفته باشد، متن الگو را
    برمی‌گرداند.

    Returns:
        متن آماده برای نمایش به بازیکن، یا None
    """
    entry = MULTILAYER_MAP.get(current_scenario_id)
    if not entry:
        return None

    available: list = []
    for ref_id in entry["references"]:
        choice = data_logger.recall_choice(ref_id)
        if choice < 0:
            continue
        quality = CHOICE_QUALITY.get(ref_id, {}).get(choice)
        if quality is None:
            continue
        available.append((ref_id, choice, quality))

    # نیاز به حداقل دو تصمیم برای دیدن الگو
    if len(available) < 2:
        return None

    # ساخت متن — فقط فهرست تصمیم‌ها، بدون نتیجه‌گیری
    lines = [entry["context"], ""]

    for ref_id, choice, _ in available:
        label = entry["labels"].get(ref_id, ref_id)
        shortcut = entry["shortcuts"].get(ref_id, {}).get(choice, "")
        if shortcut:
            lines.append(f"• {label}: {shortcut}")

    return "\n".join(lines)