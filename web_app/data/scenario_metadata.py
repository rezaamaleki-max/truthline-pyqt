def get_scenarios_for_phase(phase: int) -> list:
    """دریافت سناریوهای یک فاز خاص"""
    return [s for s in SCENARIOS_METADATA if s["phase"] == phase]


def get_competency_info(competency_key: str) -> dict | None:
    """اطلاعات کامل یک شایستگی"""
    return COMPETENCY_DEFINITIONS.get(competency_key)


def get_sub_competency_def(
    competency_key: str, sub_key: str
) -> str:
    """تعریف یک زیرمؤلفه"""
    comp = COMPETENCY_DEFINITIONS.get(competency_key)
    if not comp:
        return ""
    return comp["sub_competencies"].get(sub_key, "")


def get_full_competency_label(scenario: dict) -> str:
    """
    برچسب کامل شایستگی برای یک سناریو.
    مثال: «صداقت و یکپارچگی — شفافیت در گزارش‌دهی»
    """
    comp_key = scenario["competency"]
    sub_key = scenario["sub_competency"]
    comp_info = COMPETENCY_DEFINITIONS.get(comp_key, {})
    comp_name = comp_info.get("name_fa", comp_key)
    sub_def = get_sub_competency_def(comp_key, sub_key)
    # فقط بخش اول تعریف را به‌عنوان برچسب کوتاه می‌گیریم
    if "—" in sub_def:
        sub_label = sub_def.split("—")[0].strip()
    else:
        sub_label = sub_def.split(".")[0].strip()
    return f"{comp_name} — {sub_label}"